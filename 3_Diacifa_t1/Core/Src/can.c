/* 在 freertos.c 中定义的队列句柄：存放 CAN 发来的 AirCommand_t */
extern osMessageQueueId_t CAN_CmdQueueHandle;

/**
 * @brief  CAN RX0 中断回调（FIFO0 有消息待读）
 *         在中断上下文中执行，尽快出中断，把数据通过队列传给任务
 */
void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
    CAN_RxHeaderTypeDef rxHeader;
    uint8_t rxData[8];

    if (HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &rxHeader, rxData) != HAL_OK)
        return;

    /* 只处理气动系统命令 ID */
    if (rxHeader.StdId != CAN_AIR_CMD_STDID)
        return;

    AirCommand_t cmd = CAN_CMD_Decode(rxData, rxHeader.StdId);

    /* 放入队列，让 AirCtrl_Ta 任务处理 */
    osMessageQueuePut(CAN_CmdQueueHandle, &cmd, 0U, 0U);
}

